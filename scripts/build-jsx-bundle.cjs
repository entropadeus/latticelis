const readBabel = async () => {
  fs.mkdirSync(cacheDir, { recursive: true });
  if (fs.existsSync(babelCache)) return fs.readFileSync(babelCache, 'utf8');
  if (typeof fetch !== 'function') {
    throw new Error('fetch is unavailable; cannot download Babel standalone');
  }
  const res = await fetch(babelUrl);
  if (!res.ok) throw new Error(`failed to download Babel standalone: ${res.status}`);
  const text = await res.text();
  fs.writeFileSync(babelCache, text);
  return text;
};

const loadBabel = async () => {
  const source = await readBabel();
  const ctx = { window: null, self: null, console };
  ctx.window = ctx;
  ctx.self = ctx;
  vm.createContext(ctx);
  vm.runInContext(source, ctx, { filename: 'babel-standalone.js' });
  if (!ctx.Babel) throw new Error('Babel standalone did not initialize');
  return ctx.Babel;
};

const loadTypescriptFallback = () => {
  const globalRoot = childProcess.execFileSync('npm', ['root', '-g'], { encoding: 'utf8' }).trim();
  return require(path.join(globalRoot, 'typescript'));
};

const makeTransformer = async () => {
  try {
    const Babel = await loadBabel();
    return {
      name: 'Babel standalone',
      transform(src, file) {
        return Babel.transform(src, {
          filename: file,
          sourceType: 'script',
          presets: ['react'],
          plugins: ['transform-block-scoping'],
          comments: false,
          compact: false,
        }).code;
      },
    };
  } catch (err) {
    console.warn(`Babel standalone unavailable (${err && err.message ? err.message : err}); using TypeScript JSX fallback`);
    const ts = loadTypescriptFallback();
    return {
      name: 'TypeScript JSX fallback',
      transform(src, file) {
        const out = ts.transpileModule(src, {
          fileName: file,
          compilerOptions: {
            jsx: ts.JsxEmit.React,
            jsxFactory: 'React.createElement',
            target: ts.ScriptTarget.ES5,
            module: ts.ModuleKind.None,
            removeComments: true,
          },
        });
        if (out.diagnostics && out.diagnostics.length) {
          const msg = out.diagnostics.map(d => d.messageText).join('; ');
          throw new Error(`${file}: ${msg}`);
        }
        return out.outputText.replace(/^\"use strict\";\s*/, '');
      },
    };
  }
};

const banner = `// generated by scripts/build-jsx-bundle.cjs
// source files: ${jsxFiles.join(', ')}
// do not edit this file directly.
`;

(async () => {
  const transformer = await makeTransformer();
  fs.mkdirSync(compiledDir, { recursive: true });
  const chunks = [banner];
  for (const file of jsxFiles) {
    const abs = path.join(root, file);
    const src = fs.readFileSync(abs, 'utf8');
    const out = transformer.transform(src, file);
    chunks.push(`\n// ---- ${file} ----\n${out}\n//# sourceURL=${file}\n`);
  }
  const bundlePath = path.join(compiledDir, 'app.bundle.js');
  fs.writeFileSync(bundlePath, chunks.join('\n'), 'utf8');
  const kb = Math.round(fs.statSync(bundlePath).size / 1024);
  console.log(`built ${path.relative(root, bundlePath)} (${kb} kb) with ${transformer.name}`);
})().catch(err => {
  console.error(err && err.stack ? err.stack : err);
  process.exit(1);
});
